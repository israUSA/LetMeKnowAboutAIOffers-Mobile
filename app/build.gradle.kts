/**
 * Lee la configuración de Supabase desde `local.properties`, que está gitignoreado.
 *
 * Devuelve cadena vacía si el archivo o la clave no existen. Esto es deliberado: la app
 * NO debe fallar al compilar ni al arrancar por configuración ausente. `AppConfig` detecta
 * el valor vacío en runtime y lo rutea al estado de error de la pantalla principal, que es
 * la corrección documentada en DATA_AND_API.md.
 */
fun localProperty(key: String): String {
    val file = rootProject.file("local.properties")
    if (!file.exists()) return ""
    return Properties().apply { file.inputStream().use(::load) }.getProperty(key).orEmpty()
}

